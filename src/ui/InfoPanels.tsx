import { useEffect } from 'react';
import { Notice, Tag } from './controls';
import { fmt } from './format';
import { Lab } from './useLab';

export function ValidationPanel({ lab }: { lab: Lab }) {
  const v = lab.validation;
  useEffect(() => {
    if (!v) lab.runValidation();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
  const groups = ['ფიზიკა', 'გეომეტრია', 'ამომხსნელი'] as const;
  const pass = v ? v.checks.filter((c) => c.pass).length : 0;
  return (
    <div className="panel">
      <div className="row">
        <h3 className="grow">ვალიდაცია — იგივე შემოწმებები, რაც `npm test`-ში</h3>
        <button className="btn" onClick={lab.runValidation} disabled={v?.running}>
          {v?.running ? 'მიმდინარეობს…' : 'ხელახლა გაშვება'}
        </button>
      </div>
      {v && v.checks.length > 0 && (
        <Notice kind={pass === v.checks.length ? 'info' : 'err'}>
          {pass === v.checks.length ? '✓' : '✕'} გავიდა {pass} / {v.checks.length} შემოწმება{v.ms ? ` · ${fmt(v.ms / 1000, 1)} წმ (ფონურ ნაკადში)` : ''}
        </Notice>
      )}
      {(!v || (v.running && v.checks.length === 0)) && <p className="sub">შემოწმებები ეშვება ფონურ ნაკადში…</p>}
      {v &&
        groups.map((g) => {
          const rows = v.checks.filter((c) => c.group === g);
          if (!rows.length) return null;
          return (
            <div key={g}>
              <h3 style={{ marginBottom: 6 }}>{g}</h3>
              <div className="table-wrap">
                <table className="data">
                  <thead>
                    <tr>
                      <th>შემოწმება</th>
                      <th>მოსალოდნელი</th>
                      <th>მიღებული</th>
                      <th>შედეგი</th>
                    </tr>
                  </thead>
                  <tbody>
                    {rows.map((c) => (
                      <tr key={c.id}>
                        <td>{c.title}</td>
                        <td style={{ whiteSpace: 'normal' }}>{c.expected}</td>
                        <td style={{ whiteSpace: 'normal' }}>{c.actual}</td>
                        <td>{c.pass ? <span className="status-pass">✓ გავიდა</span> : <span className="status-fail">✕ ჩავარდა</span>}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          );
        })}
    </div>
  );
}

